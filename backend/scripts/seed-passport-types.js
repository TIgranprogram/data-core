async function main() {
  const [parts, types] = await Promise.all([api('GET', '/api/dicts/passportParts'), api('GET', '/api/dicts/passportTypes')]);
  const have = new Set((parts.items || []).map((p) => p.name));
  const haveTypes = new Set((types.items || []).map((t) => t.name));
  const newParts = PARTS.filter(([name]) => !have.has(name));
  const newTypes = TYPES.filter(([name]) => !haveTypes.has(name));
  console.log(`Части добавить: ${newParts.length}: ${newParts.map((p) => p[0]).join(', ')}`);
  console.log(`Типы добавить: ${newTypes.length} из ${TYPES.length}`);
  for (const [name, category, , rows] of newTypes) console.log(`  ${category} ${name}: ${rows.map(([p, , s]) => (s ? `${p} ${s}` : p)).join(', ')}`);
  if (!APPLY) { console.log('\nНичего не записано (план). Записать: --apply'); return; }
  for (const [name, genSingular, genPlural] of newParts) await api('POST', '/api/dicts/passportParts', { name, genSingular, genPlural });
  for (const [name, category, words, rows, coats = ['COAT_POWDER']] of newTypes) {
    await api('POST', '/api/dicts/passportTypes', { name, category, words, composition: rows.map((r) => r.join('; ')).join('\n'), coatings: coats.join(', ') });
  }
  console.log(`\nГотово: частей ${newParts.length}, типов ${newTypes.length}.`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
