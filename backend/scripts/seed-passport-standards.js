(async () => {
  const uri = process.env.MONGO_URI;
  if (!uri) throw new Error('MONGO_URI не задан');
  const client = await MongoClient.connect(uri);
  const db = client.db(process.env.MONGO_DB || undefined);
  const c = db.collection('dict_values');
  const have = new Set((await c.find({ dict: 'passportStandards', deletedAt: null }, { projection: { code: 1 } }).toArray()).map((d) => d.code));
  const add = ROWS.filter(([code]) => !have.has(code));
  console.log(`База ${db.databaseName}: нормативов есть ${have.size}, добавить ${add.length}${add.length ? ': ' + add.map((r) => r[0]).join(', ') : ''}`);
  if (process.argv.includes('--apply') && add.length) {
    const now = new Date();
    const r = await c.insertMany(add.map(([code, name, title, status, applies]) => ({ dict: 'passportStandards', code, name, title, status, checkedAt: CHECKED, applies, deletedAt: null, createdAt: now, updatedAt: now })));
    console.log(`Добавлено: ${r.insertedCount}`);
  } else if (add.length) console.log('Ничего не записано (план). Записать: --apply');
  await client.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
