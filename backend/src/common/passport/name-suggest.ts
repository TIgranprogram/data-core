const TRAINER_NAME = /тренаж|жим|тяга|присед|подтяг|вело|степ|орбитрек|эллип|твист|диск|хипс|шейкер|маятник|скороход|гравитрон|мультиштанг|гребная|бицепс|трицепс|сведен|лыжник|покрышк|разгибан|сгибан|ног/i;
