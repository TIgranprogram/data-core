export function relationView(id, visible = () => true) {
  const ids = Object.keys(SECTIONS).filter(visible);
  const selected = ids.includes(id) ? id : ids[0];
  const edges = RELATIONS.filter(([a, b]) => ids.includes(a) && ids.includes(b));
  return { ids, selected, incoming: edges.filter(([, b]) => b === selected), outgoing: edges.filter(([a]) => a === selected) };
}
