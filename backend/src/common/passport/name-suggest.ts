const PURPOSE_DIO: Rule[] = [
  [/качел|карусел|качалк|балансир|песочниц|игров|горка|сетка/i, 'Игровое'],
];

function first(rules: Rule[], text: string): Hit | null | undefined {
  for (const [re, value] of rules) {
    const m = text.match(re);
    if (!m) continue;
    if (value == null) return null;
    return { value, word: m[0] };
  }
  return undefined;
}

/** Имена элементов справочника или null (нет правила / правило запретило: навес, трибуны). */
export function suggestElementNames(name: string, cat: string, group = ''): ElementSuggest | null {
  const title = String(name ?? '');
  const one = first(SINGLE, title);
  if (one === null) return null;
  if (one) return { names: [one.value], word: one.word, how: 'по названию' };
  if (cat === 'TRN' && TRAINER_NAME.test(title) && !PRESS.test(title)) {
    const t = first(TRAINER, title);
    if (t) return { names: [t.value], word: t.word, how: 'тренажёр по названию' };
  } else if (group === 'Воркаут' || WORKOUT_NAME.test(title)) {
    const cleaned = title.replace(/комплекс воркаут/i, '');
    if (!UNCOVERED.test(cleaned)) {
      const names: string[] = [];
      let word = '';
      for (const [re, el] of TOKENS) {
        const m = el ? cleaned.match(re) : null;
        if (m && el && !names.includes(el)) { names.push(el); if (!word) word = m[0]; }
      }
      if (names.includes('Скамья для пресса')) {
        const i = names.indexOf('Скамья');
        if (i >= 0) names.splice(i, 1);
      }
      if (names.length) return { names, word, how: 'состав по названию' };
    }
  }
  return null;
}

/** Имя варианта раздела «Назначение» или null. У благоустройства без слова в названии — «Прочее благоустройство», если группа так называется. */
export function suggestPurposeName(name: string, cat: string, group = ''): PurposeSuggest | null {
  const title = String(name ?? '');
  let hit: Hit | null | undefined;
  if (cat === 'TRN') hit = first(PURPOSE_TRN, title);
  else if (cat === 'BLG') {
    hit = first(PURPOSE_BLG, title);
    if (!hit && /^Благоустройство/.test(group)) hit = { value: 'Прочее благоустройство', word: '' };
  } else if (cat === 'DIO') hit = first(PURPOSE_DIO, title);
  else if (cat === 'WRK') hit = first(PURPOSE, title) || first(PURPOSE_BLG, title);
  if (!hit?.value) return null;
  return { name: hit.value, word: hit.word };
}
