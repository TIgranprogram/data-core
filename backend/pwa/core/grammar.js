/** Сторож грамматики текстов на экране (пользователь 2026-11-13: «из вид «Информационный стенд»» — ошибка склонения).
 *  Ловит частые сбои сборки фраз из кусков, а не всю грамматику:
 *   - падеж после предлога: «из вид», «для группа», «без изделие», «по группа», «в категория» …;
 *   - одно и то же слово два раза подряд: «в в», «тип тип».
 *  Список слов — те, что приложение подставляет в шаблоны строк (сущности учёта). Добавили новое слово в шаблон «из ${…}» —
 *  добавьте его сюда. Используют: tools/site-audit.mjs (правило gr, текст экрана), tools/ai-tester (авто-находки),
 *  backend/src/pwa-guards.spec.ts (строки в исходниках pwa). Без зависимостей — работает и в браузере, и в Node. */

/** Слово в именительном падеже, у которого родительный/предложный другой (ошибка видна сразу). */
const NOUNS = ['вид', 'группа', 'раздел', 'категория', 'изделие', 'справочник', 'заказ', 'паспорт', 'тип', 'элемент', 'склад',
  'позиция', 'заявка', 'компания', 'поставщик', 'материал', 'шаблон', 'документ', 'сотрудник', 'серия', 'признак', 'покупатель'];
/** После этих предлогов именительный падеж невозможен (родительный / дательный / предложный). */
const GEN = ['из', 'для', 'от', 'до', 'без', 'у', 'около', 'после', 'кроме', 'вместо', 'среди', 'возле', 'по', 'к', 'о', 'об', 'при'];
/** «в» / «на» + женский род в именительном («в группа», «на позиция») — всегда ошибка (мужской «в раздел» бывает верным). */
const LOC_FEM = ['группа', 'категория', 'позиция', 'заявка', 'компания', 'серия'];

const L = '\\p{L}';
const word = (list) => `(?:${list.join('|')})`;
const end = `(?=$|[^${L}])`;
const start = `(?:^|[^${L}])`;

export const GRAMMAR = [
  { re: new RegExp(`${start}(${word(GEN)})\\s+(${word(NOUNS)})${end}`, 'iu'), hint: 'после предлога слово не в том падеже' },
  { re: new RegExp(`${start}((?:в|на))\\s+(${word(LOC_FEM)})${end}`, 'iu'), hint: 'после «в / на» слово не в том падеже' },
  // только русские слова и не перед дефисом: CSS-классы «crumb crumb-group» — не текст
  { re: new RegExp(`${start}([а-яё]{1,20})\\s+\\1(?=$|[^${L}\\-])`, 'iu'), hint: 'слово повторено два раза подряд' },
];

/** grammarSlips(text) → [{ text: фрагмент, hint }]; пусто — ошибок не найдено. */
export function grammarSlips(text) {
  if (typeof text !== 'string' || !text.trim()) return [];
  const out = [];
  for (const g of GRAMMAR) {
    const m = text.match(g.re);
    if (m) out.push({ text: m[0].trim(), hint: g.hint });
  }
  return out;
}

/** Источники регулярных выражений — для вставки в браузерный скрипт обхода (site-audit / ai-tester). */
export const GRAMMAR_SRC = GRAMMAR.map((g) => ({ src: g.re.source, flags: g.re.flags, hint: g.hint }));

/** Строка «Дальше: …» (Ф3, C112): одно двоеточие. Лишние двоеточия внутри подсказки («уточните: нагрузка») становятся тире. */
export const nextLine = (text) => `Дальше: ${String(text ?? '').trim().replace(/\s*:\s*/g, ' — ').replace(/\s{2,}/g, ' ')}`;
