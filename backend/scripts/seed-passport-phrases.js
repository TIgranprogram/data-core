(async () => {
  const apply = process.argv.includes('--apply');
  const c = await MongoClient.connect(process.env.MONGO_URI);
  const coll = c.db(process.env.MONGO_DB || undefined).collection('dict_values');
  const have = new Set((await coll.find({ dict: 'passportPhrases' }).toArray()).map((d) => `${d.section}|${d.categories}|${d.name}`));
  const add = ROWS.filter((r) => !have.has(`${r.section}|${r.categories}|${r.name}`));
  console.log(`Готовые тексты паспорта: есть ${have.size}, добавить ${add.length} (назначение ${add.filter((r) => r.section === 'purpose').length}, установка ${add.filter((r) => r.section === 'installation').length})`);
  if (apply && add.length) {
    const now = new Date();
    await coll.insertMany(add.map((r) => ({ dict: 'passportPhrases', ...r, deletedAt: null, createdAt: now, updatedAt: now })));
    console.log(`Записано: ${add.length}`);
  } else if (!apply) console.log('Ничего не записано (план). Записать: --apply');
  await c.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
