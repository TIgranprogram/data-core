// Изолированная приёмка реального UI. Все API запусков перехвачены: процессов тестировщика нет.
import { chromium } from '../../tools/design-checks/node_modules/playwright-core/index.mjs';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import * as catalog from '../catalog.mjs';
import { createPult } from '../server.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'pult-ui-'));
fs.mkdirSync(path.join(root,'backend/scripts'),{recursive:true});
const pult = createPult({root,machine:{},statusFn:async()=>({})});
const port = await pult.listen(0);
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const out = path.resolve('docs/crew/C091-pult-test-flow');
const errors = []; page.on('pageerror',e=>errors.push(e.message));
let state = 'empty'; const calls=[];
const status = () => ({gateFiles:[],branch:'fixture',runs:{},advice:{items:[]},tester:{state,active:['running','stopping'].includes(state),busy:['running','stopping','preparing'].includes(state),report: state==='finished'?{path:'tools/logs/ai-tester/2026-11-12/REPORT.md'}:null}});
await page.route('**/api/catalog', r=>r.fulfill({json:{groups:catalog.GROUPS,sections:catalog.SECTIONS,risks:catalog.RISKS,switches:[],levels:[],problems:[],commands:catalog.COMMANDS.map(({run,...c})=>({...c,blocked:[],kind:'job',params:c.params||[]}))}}));
await page.route('**/api/status', r=>r.fulfill({json:status()}));
await page.route('**/api/run', r=>{ const body=r.request().postDataJSON(); calls.push(body); if(body.id==='ait-run')state='running';if(body.id==='ait-stop')state='stopping';return r.fulfill({json:{opened:true}}); });
try {
 await page.goto(`http://127.0.0.1:${port}/`);
 await page.getByRole('button',{name:/ИИ-тестировщик/}).click();
 await page.getByRole('heading',{name:'Проверок ещё нет'}).waitFor();
 await page.getByRole('button',{name:'Результаты',exact:true}).click();
 assert.equal(calls.at(-1).id,'ait-report');
 await page.locator('.tester-main select').selectOption('20');
 await page.getByRole('button',{name:'Проверить сайт',exact:true}).click();
 await page.getByRole('heading',{name:'Проверка работает'}).waitFor();
 assert.deepEqual(calls.at(-1),{id:'ait-run',params:{minutes:'20'}});
 assert.ok(await page.getByRole('button',{name:'Проверить сайт',exact:true}).isDisabled());
 await page.screenshot({path:path.join(out,'ui-running-wide.png'),fullPage:true});
 await page.getByRole('button',{name:'Остановить',exact:true}).click();
 await page.getByRole('heading',{name:'Останавливаем проверку'}).waitFor();
 assert.ok(await page.getByRole('button',{name:'Остановить',exact:true}).isDisabled());
 state='failed'; await page.locator('#refresh').click();
 await page.getByRole('heading',{name:'Подготовка или запуск не удались'}).waitFor();
 await page.setViewportSize({width:1024,height:900});
 await page.emulateMedia({colorScheme:'dark'});
 await page.screenshot({path:path.join(out,'ui-failed-narrow-dark.png'),fullPage:true});
 state='finished';await page.locator('#refresh').click();
 await page.getByRole('heading',{name:'Проверка закончена'}).waitFor();
 await page.getByText('Дополнительно',{exact:true}).click();
 assert.ok(await page.getByRole('button',{name:'Готовность',exact:true}).isVisible()); // C088: готовность — в главной панели, первой
 await page.getByText('Дополнительно',{exact:true}).click();
 await page.getByRole('button',{name:'Результаты',exact:true}).click();
 assert.equal(calls.at(-1).id,'ait-report');
 await page.screenshot({path:path.join(out,'ui-finished-narrow-dark.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: empty/report, duration/start, running/repeat disabled, stop pending, failed, finished/report, extras; 1440 light / 1024 dark; no page errors or horizontal overflow.');
} finally { await browser.close(); await pult.close(); }
