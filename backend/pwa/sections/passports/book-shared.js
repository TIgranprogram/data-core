export function aiPrompt({ pages }) {
  const body = pages.map((t, i) => `=== Страница ${i + 1} ===\n${String(t).replace(/\n{3,}/g, '\n\n').trim()}`).join('\n\n');
  return [
    'ЗАДАНИЕ: сразу список готовых правок по паспорту ниже. Не переспрашивай. Не давай советов «проверьте сами». Только куда кликнуть и что поставить.',
    ...TASK, '',
    '--- НАЧАЛО ПАСПОРТА ---', body, '--- КОНЕЦ ПАСПОРТА ---',
  ].join('\n');
}

/**
 * Узкий промпт раздела (части/материалы/габариты/монтаж) под фото в чате.
 * @param {{ kind: 'parts'|'materials'|'dims'|'install', productLabel?: string, rowsText?: string, allowParts?: string[], allowMats?: string[] }} p
 */
export function aiFocusPrompt(p) {
  const f = FOCUS[p.kind] || FOCUS.materials;
  const lines = [
    `ЗАДАНИЕ: заполнение «${f.title}» по прикреплённым фото/чертежу. Сразу готовые правки — куда кликнуть и что вписать.`,
    ...RULES.slice(0, 7),
    `Где кликать: ${f.where}.`,
    ...f.ask,
    p.productLabel ? `Изделие: ${p.productLabel}.` : '',
    p.rowsText ? `Сейчас в таблице / полях:\n${p.rowsText}` : 'Сейчас таблица пуста или поля не заполнены.',
    p.allowParts?.length ? `Допустимые части (предпочитай эти):\n${p.allowParts.slice(0, 40).map((x) => `• ${x}`).join('\n')}` : '',
    p.allowMats?.length ? `Допустимые материалы (предпочитай эти):\n${p.allowMats.slice(0, 40).map((x) => `• ${x}`).join('\n')}` : '',
    'Пример строки: «Сначала → Части у материалов | Строка 1 | ВПИСАТЬ: часть «стойка»; материал «труба электросварная»; размеры «∅89×3»»',
    'Конец: Итог: N правок. Или: Правок нет (на фото не видно).',
  ].filter(Boolean);
  return lines.join('\n');
}

/** Скопировать текст промпта; вернуть короткое сообщение для подсказки. */
export async function copyAiText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return 'Скопировано. Вставьте в чат ИИ и прикрепите фото — ответ: куда кликнуть и что вписать.';
  } catch {
    return 'Браузер не дал скопировать. Попробуйте ещё раз.';
  }
}

/** Текст листа: только то, что печатается в PDF (без кнопок, загрузчиков, подсказок и пояснений интерфейса). */
export function pageText(el) {
  const c = el.cloneNode(true);
  c.querySelectorAll('button, input, select, textarea, [class*="photo"], [class*="drop"], .bk-ed, .bk-mark, .bk-noimg, .bk-pno, .bk-keys, .bk-ui, .muted, .hint').forEach((x) => x.remove());
  c.classList.add('bk-measure'); c.style.setProperty('--w', el.offsetWidth + 'px');
  document.body.append(c);
  const t = c.innerText.split('\n').filter((l) => l.trim() && !/^[×🖼]$/u.test(l.trim())).join('\n');
  c.remove();
  return t;
}

/** Одно действие над паспортом за раз; занято — ошибка, а не молчаливый пропуск (иначе «Сохранено» без записи). */
export async function exclusive(id, passportAction, fn) {
  let ran = false;
  const res = await passportAction(id, async () => { ran = true; return fn(); });
  if (!ran) throw new Error('Дождитесь завершения предыдущего действия и повторите');
  return res;
}

