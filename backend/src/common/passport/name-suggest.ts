/**
 * Подсказка элементов и назначения по названию изделия (C062, C078).
 * Те же правила, что в `scripts/c062-passport-purpose-plan.js`: первое совпадение, неуверенное не возвращаем.
 * Пишет в изделие только экран после «Да, верно» — здесь лишь имя варианта справочника.
 */

export interface ElementSuggest { names: string[]; word: string; how: string }
export interface PurposeSuggest { name: string; word: string }

type Rule = [RegExp, string | null];
type Hit = { value: string; word: string };

